#!/usr/bin/env python3
"""Audit recorder exclusions against the entity registry; --write refreshes the include.

Run after adding/renaming OpenWrt entities. Review the diff, run ha core check,
then restart Core to activate a changed recorder filter. No restart or purge is
performed by this tool. Unknown/mobile trackers are deliberately retained.
"""
from __future__ import annotations

import argparse
import collections
import fnmatch
import json
from pathlib import Path
import re

import yaml

ROOT = Path('/config')
OUTPUT = ROOT / 'recorder_excluded_entities.yaml'
KUMA_SUFFIXES = ('_uptime_30d', '_uptime_365d', '_avg_response_time_1d',
                 '_avg_response_time_30d', '_avg_response_time_365d')
FIXED = re.compile(r'shelly|chromecast|roborock|siemens|dishwasher|diskmaskin|canon|'
                   r'prusa|broadlink|home.assistant.voice|gw.august|levoit|'
                   r'golvv[aä]rme|taklamp|blomlamp|v[aä]xtlamp|vattensensor|'
                   r'ventilfl[aä]kt|billaddare|ljussensor|hemmabio.el|'
                   r'(^|[ _-])ap[ _-]|switch|sw_vinden|heimdal|tor.home.arpa|mimer', re.I)


def inventory():
    entities = json.loads((ROOT / '.storage/core.entity_registry').read_text())['data']['entities']
    devices = {d['id']: d for d in json.loads((ROOT / '.storage/core.device_registry').read_text())['data']['devices']}
    people = json.loads((ROOT / '.storage/person').read_text())['data']['items']
    protected = {eid for p in people for eid in p.get('device_trackers', [])}
    selected = {'sensor.thread_natverksdiagnostik': 'existing exclusion'}
    kept_trackers = []
    for e in entities:
        eid = e['entity_id']
        if e['platform'] == 'uptime_kuma' and e['unique_id'].endswith(KUMA_SUFFIXES):
            selected[eid] = 'Kuma rolling aggregate'
        if e['platform'] != 'openwrt':
            continue
        if eid.startswith('sensor.'):
            selected[eid] = 'OpenWrt sensor'
        elif eid.startswith('device_tracker.'):
            d = devices.get(e.get('device_id'), {})
            label = ' '.join(str(v or '') for v in [eid, d.get('name'), d.get('name_by_user')])
            fixed = bool(FIXED.search(label)) or d.get('manufacturer') in {'Shelly', 'Espressif', 'Tuya'}
            if eid not in protected and fixed:
                selected[eid] = 'OpenWrt fixed device tracker'
            else:
                kept_trackers.append(eid)
    return entities, selected, sorted(kept_trackers), protected


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    entities, selected, kept, protected = inventory()
    if args.write:
        lines = ['# Generated by tools/recorder_filter_audit.py --write.',
                 '# Registry entity IDs are independent of Swedish display names.',
                 '# Person trackers and unidentified/mobile OpenWrt clients are retained.',
                 '# Refresh after entity additions/renames; validate and restart Core.',
                 '# Removing a sensor from recorder also stops its future statistics.']
        for eid, reason in sorted(selected.items()):
            lines.append(f'- {eid}  # {reason}')
        OUTPUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    configured = set(yaml.safe_load(OUTPUT.read_text()))
    # Inspect literal globs without constructing HA's !secret/!include tags.
    root = yaml.compose((ROOT / 'configuration.yaml').read_text())
    def child(node, key):
        return next(v for k, v in node.value if k.value == key)
    exclude = child(child(root, 'recorder'), 'exclude')
    globs = [n.value for n in child(exclude, 'entity_globs').value]
    domains = {n.value for n in child(exclude, 'domains').value}
    def excluded(eid):
        return eid in configured or eid.split('.')[0] in domains or any(fnmatch.fnmatchcase(eid, p) for p in globs)
    missing = sorted(eid for eid in selected if not excluded(eid))
    accidental = sorted(eid for eid in protected | set(kept) if excluded(eid))
    report = {
        'selected': dict(collections.Counter(selected.values())),
        'selected_enabled': dict(collections.Counter(selected[e['entity_id']] for e in entities if e['entity_id'] in selected and not e.get('disabled_by'))),
        'missing_exclusions': missing,
        'accidentally_excluded_protected_trackers': accidental,
        'retained_openwrt_trackers': kept,
        'refresh_required': sorted(set(selected) - configured),
    }
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return int(bool(missing or accidental))


if __name__ == '__main__':
    raise SystemExit(main())
